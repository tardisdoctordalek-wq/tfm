/* 타일은 스테이지 테마(들판/동굴/하늘)마다 색이 바뀝니다.
 * 그래서 타일 그림은 색 글자 대신 "톤 번호"로 그립니다.
 *   1 2 3 4 = 주 재질의 밝음 / 기본 / 그늘 / 최암부
 *   5 6 7 8 = 보조 재질(잔디, 장식 등)의 밝음 / 기본 / 그늘 / 최암부
 * 테마 램프를 넣어 주면 그때 실제 색이 정해집니다.
 *
 *   drawPixels(ctx, DIRT, x, y, 2, false, tonePal(theme.dirt, theme.grass));
 */
function tonePal(main, sub) {
  const m = main || [], s = sub || [];
  return {
    '.': null,
    1: m[0], 2: m[1], 3: m[2], 4: m[3],
    5: s[0], 6: s[1], 7: s[2], 8: s[3],
  };
}
